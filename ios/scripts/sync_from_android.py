#!/usr/bin/env python3
"""Generates the iPhone app's strings and colour palettes from the Android sources, so both apps show the same words
in the same eight languages and the same colours. Android stays the single source of truth: edit strings.xml or
Color.kt, then run this script (CI fails if the generated files are out of date).

    python3 ios/scripts/sync_from_android.py          # write
    python3 ios/scripts/sync_from_android.py --check  # verify only (CI)

Outputs
  ios/Yaadein/Resources/<lang>.lproj/Localizable.strings      every <string> and <string-array> item (name_0, name_1...)
  ios/Yaadein/Resources/<lang>.lproj/Localizable.stringsdict  every <plurals>
  ios/Yaadein/DesignSystem/Generated/Palettes.generated.swift the five palettes, avatar colours and cover gradients
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
IOS = os.path.join(ROOT, "ios", "Yaadein")
# Android resource qualifier -> iOS lproj folder.
LOCALES = {"values": "en", "values-hi": "hi", "values-mr": "mr", "values-gu": "gu", "values-ta": "ta",
           "values-te": "te", "values-bn": "bn", "values-kn": "kn"}
MODULE_ORDER = ["core/ui", "app"]  # then every feature module alphabetically; later modules win on duplicate names


def modules():
    found = []
    for base in ("core", "feature"):
        for name in sorted(os.listdir(os.path.join(ROOT, base))):
            path = f"{base}/{name}"
            if os.path.isdir(os.path.join(ROOT, path, "src", "main", "res")):
                found.append(path)
    found.append("app")
    ordered = [m for m in MODULE_ORDER if m in found] + [m for m in found if m not in MODULE_ORDER]
    return ordered


def android_text(el):
    """The value Android would show: unquote, collapse whitespace outside quotes, unescape."""
    raw = "".join(el.itertext())
    out, quoted, i = [], False, 0
    while i < len(raw):
        c = raw[i]
        if c == "\\" and i + 1 < len(raw):
            n = raw[i + 1]
            out.append({"n": "\n", "t": "\t", "'": "'", '"': '"', "\\": "\\", "@": "@", "?": "?"}.get(n, n))
            i += 2
            continue
        if c == '"':
            quoted = not quoted
            i += 1
            continue
        if c.isspace() and not quoted:
            if not out or out[-1] != " ":
                out.append(" ")
            i += 1
            continue
        out.append(c)
        i += 1
    return "".join(out).strip()


SPEC = re.compile(r"%(\d+\$)?([sd])")


def to_ios_format(text):
    """%1$s -> %1$@ and %s -> %@; %d stays. Android's %% is already the iOS escape."""
    return SPEC.sub(lambda m: "%" + (m.group(1) or "") + ("@" if m.group(2) == "s" else "d"), text)


def strings_escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def xml_escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def collect(qualifier):
    strings, plurals = {}, {}
    for module in modules():
        folder = os.path.join(ROOT, module, "src", "main", "res", qualifier)
        if not os.path.isdir(folder):
            continue
        for file in sorted(os.listdir(folder)):
            if not file.endswith(".xml"):
                continue
            tree = ET.parse(os.path.join(folder, file))
            for el in tree.getroot():
                name = el.get("name")
                if el.tag == "string":
                    strings[name] = to_ios_format(android_text(el))
                elif el.tag == "string-array":
                    for i, item in enumerate(el.findall("item")):
                        strings[f"{name}_{i}"] = to_ios_format(android_text(item))
                    strings[f"{name}_count"] = str(len(el.findall("item")))
                elif el.tag == "plurals":
                    plurals[name] = {item.get("quantity"): to_ios_format(android_text(item)) for item in el.findall("item")}
    return strings, plurals


HEADER = "/* GENERATED by ios/scripts/sync_from_android.py from the Android strings.xml files. Do not edit. */\n"


def render_strings(strings):
    lines = [HEADER]
    for key in sorted(strings):
        lines.append(f'"{key}" = "{strings_escape(strings[key])}";')
    return "\n".join(lines) + "\n"


def render_plurals(plurals):
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
           "<!-- GENERATED by ios/scripts/sync_from_android.py from the Android strings.xml files. Do not edit. -->",
           '<plist version="1.0">', "<dict>"]
    for key in sorted(plurals):
        forms = plurals[key]
        out += [f"    <key>{key}</key>", "    <dict>",
                "        <key>NSStringLocalizedFormatKey</key>", "        <string>%#@value@</string>",
                "        <key>value</key>", "        <dict>",
                "            <key>NSStringFormatSpecTypeKey</key>", "            <string>NSStringPluralRuleType</string>",
                "            <key>NSStringFormatValueTypeKey</key>", "            <string>d</string>"]
        for quantity in ("zero", "one", "two", "few", "many", "other"):
            if quantity in forms:
                # The plural selector consumes argument 1; the text keeps its own %1$d / %2$@ positions.
                out += [f"            <key>{quantity}</key>", f"            <string>{xml_escape(forms[quantity])}</string>"]
        out += ["        </dict>", "    </dict>"]
    out += ["</dict>", "</plist>"]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- palettes

COLOR_KT = os.path.join(ROOT, "core/ui/src/main/kotlin/com/yaadein/core/ui/theme/Color.kt")
ROLES = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "secondary", "onSecondary",
         "secondaryContainer", "onSecondaryContainer", "tertiary", "onTertiary", "tertiaryContainer",
         "onTertiaryContainer", "error", "onError", "errorContainer", "onErrorContainer", "background", "onBackground",
         "surface", "onSurface", "surfaceVariant", "onSurfaceVariant", "outline", "outlineVariant", "inverseSurface",
         "inverseOnSurface", "inversePrimary", "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer",
         "surfaceContainerHigh", "surfaceContainerHighest"]
# Material 3 baseline values Compose uses for roles a palette leaves out (lightColorScheme()/darkColorScheme()).
M3_DEFAULTS = {
    False: {"error": 0xFFB3261E, "onError": 0xFFFFFFFF, "errorContainer": 0xFFF9DEDC, "onErrorContainer": 0xFF8C1D18,
            "inverseSurface": 0xFF322F35, "inverseOnSurface": 0xFFF5EFF7, "inversePrimary": 0xFFD0BCFF},
    True: {"error": 0xFFF2B8B5, "onError": 0xFF601410, "errorContainer": 0xFF8C1D18, "onErrorContainer": 0xFFF9DEDC,
           "inverseSurface": 0xFFE6E0E9, "inverseOnSurface": 0xFF322F35, "inversePrimary": 0xFF6750A4},
}
PALETTES = [("WarmAlbum", "warmAlbum", "warmAvatars"), ("Midnight", "midnight", "midnightAvatars"),
            ("Monsoon", "monsoon", "monsoonAvatars"), ("Festive", "festive", "festiveAvatars"),
            ("MinimalMono", "minimalMono", "monoAvatars")]


def parse_scheme(block, dark):
    values = {k: int(v, 16) for k, v in re.findall(r"(\w+)\s*=\s*Color\(0x([0-9A-Fa-f]{8})\)", block)}
    for role, default in M3_DEFAULTS[dark].items():
        values.setdefault(role, default)
    missing = [r for r in ROLES if r not in values]
    if missing:
        raise SystemExit(f"Color.kt: scheme is missing {missing}")
    return values


def parse_palettes():
    src = open(COLOR_KT, encoding="utf-8").read()
    result = []
    for kotlin_name, swift_name, avatars_name in PALETTES:
        m = re.search(rf"val {kotlin_name}: ThemePalette = run \{{(.*?)\n\}}", src, re.S)
        if not m:
            raise SystemExit(f"Color.kt: palette {kotlin_name} not found")
        body = m.group(1)
        light = re.search(r"lightColorScheme\((.*?)\n    \)", body, re.S).group(1)
        dark = re.search(r"darkColorScheme\((.*?)\n    \)", body, re.S).group(1)
        av = re.search(rf"private val {avatars_name} = listOf\((.*?)\)\n", src, re.S).group(1)
        avatars = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{8})", av)]
        result.append((swift_name, parse_scheme(light, False), parse_scheme(dark, True), avatars))
    grad = re.search(r"return mapOf\((.*?)\n    \)", src, re.S).group(1)
    gradients = [(k, int(a, 16), int(b, 16)) for k, a, b in
                 re.findall(r'"(\w+)" to \(Color\(0x([0-9A-Fa-f]{8})\) to Color\(0x([0-9A-Fa-f]{8})\)\)', grad)]
    return result, gradients


def render_palettes():
    palettes, gradients = parse_palettes()
    hx = lambda v: f"0x{v:08X}"
    out = ["// GENERATED by ios/scripts/sync_from_android.py from core/ui/.../theme/Color.kt. Do not edit.",
           "// Colours are ARGB like Compose's Color(0xAARRGGBB).", "",
           "struct SchemeHex {"]
    out += [f"    let {r}: UInt32" for r in ROLES]
    out += ["}", "", "struct PaletteHex {", "    let light: SchemeHex", "    let dark: SchemeHex",
            "    let avatars: [UInt32]", "}", "", "enum GeneratedPalettes {"]
    for name, light, dark, avatars in palettes:
        out.append(f"    static let {name} = PaletteHex(")
        for label, scheme in (("light", light), ("dark", dark)):
            out.append(f"        {label}: SchemeHex(")
            out.append(",\n".join(f"            {r}: {hx(scheme[r])}" for r in ROLES))
            out.append("        ),")
        out.append(f"        avatars: [{', '.join(hx(a) for a in avatars)}]")
        out.append("    )")
    out.append("")
    out.append("    /// Fixed cover gradients for text-only memories (keys match CoverStyle). \"theme\" and \"accent\" are derived")
    out.append("    /// from the palette in code, exactly as gradientsFor() does on Android.")
    out.append("    static let gradients: [String: (UInt32, UInt32)] = [")
    out += [f'        "{k}": ({hx(a)}, {hx(b)}),' for k, a, b in gradients]
    out += ["    ]", "}", ""]
    return "\n".join(out)


def outputs():
    files = {}
    for qualifier, lang in LOCALES.items():
        strings, plurals = collect(qualifier)
        if lang != "en":
            # Android falls back to English for anything untranslated; iOS does the same through the en table.
            pass
        files[os.path.join(IOS, "Resources", f"{lang}.lproj", "Localizable.strings")] = render_strings(strings)
        files[os.path.join(IOS, "Resources", f"{lang}.lproj", "Localizable.stringsdict")] = render_plurals(plurals)
    files[os.path.join(IOS, "DesignSystem", "Generated", "Palettes.generated.swift")] = render_palettes()
    return files


def main():
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs().items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == content:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            print("wrote", os.path.relpath(path, ROOT))
    if stale:
        print("Out of date (run python3 ios/scripts/sync_from_android.py):\n  " + "\n  ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
