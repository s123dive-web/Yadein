#!/usr/bin/env python3
"""Regenerates core/domain/src/main/resources/festivals/festivals.csv from the `holidays` package (pip install holidays).

Usage: python3 scripts/festivals/generate.py > core/domain/src/main/resources/festivals/festivals.csv
The table is bundled; the app never computes lunar dates or downloads anything.
"""
import holidays

MAP = {
    'diwali': ['Diwali (Deepavali)'], 'holi': ['Holi'], 'ganesh_chaturthi': ['Ganesh Chaturthi'], 'dussehra': ['Dussehra'],
    'raksha_bandhan': ['Raksha Bandhan'], 'gudi_padwa': ['Gudi Padwa'], 'makar_sankranti': ['Makar Sankranti'],
    'eid_al_fitr': ['Id-ul-Fitr'], 'eid_al_adha': ['Id-ul-Zuha'], 'christmas': ['Christmas'], 'new_year': ["New Year's Day"],
    'independence_day': ['Independence Day'], 'republic_day': ['Republic Day'], 'janmashtami': ['Janmashtami (Vaishnava)'],
    'guru_nanak_jayanti': ["Guru Nanak's Jayanti"],
}
EXACT = {'holi', 'dussehra', 'christmas'}  # otherwise "Holika Dahan", "Dussehra (Saptami)", "Christmas Eve" would match

print('# Yaadein festival table, generated by scripts/festivals/generate.py from the `holidays` Python package (MIT, v%s).' % holidays.__version__)
print('# festival,year,date. Islamic dates past the published calendars are marked (estimated) upstream; see docs/FESTIVALS.md.')
print('festival,year,date')
for year in range(2010, 2036):
    table = holidays.India(years=year, categories=('public', 'optional'))
    for key, needles in MAP.items():
        for day, name in sorted(table.items()):
            parts = [p.strip().replace(' (estimated)', '') for p in name.split(';')]
            if any((p == needles[0]) if key in EXACT else any(p.startswith(n) for n in needles) for p in parts):
                print(f'{key},{year},{day.isoformat()}')
                break
